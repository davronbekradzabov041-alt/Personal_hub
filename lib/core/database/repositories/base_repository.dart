/// Базовый контракт репозитория.
///
/// Любой репозиторий — ядра или будущего модуля — реализует
/// этот интерфейс. Это даёт единообразный CRUD-API и позволяет,
/// например, глобальному поиску (Этап 5) работать с разными
/// репозиториями по одному и тому же контракту.
abstract class BaseRepository<T> {
  /// Добавить новую запись, возвращает присвоенный id.
  Future<int> add(T item);

  /// Обновить существующую запись.
  Future<void> update(T item);

  /// Удалить запись по id. Возвращает true, если запись существовала.
  Future<bool> delete(int id);

  /// Получить одну запись по id.
  Future<T?> getById(int id);

  /// Получить все записи.
  Future<List<T>> getAll();
}
