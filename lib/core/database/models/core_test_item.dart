import 'package:isar/isar.dart';

part 'core_test_item.g.dart';

/// Тестовая коллекция ядра.
///
/// Это НЕ модуль и не относится к Расписанию/Финансам/и т.д.
/// Единственная цель — проверить, что запись/чтение через Isar
/// работает, и дать Этапу 5 (глобальный поиск) реальные данные
/// для поиска до появления настоящих модулей.
///
/// Когда появятся модули со своими коллекциями, этот файл
/// можно будет удалить без каких-либо последствий для core/.
@collection
class CoreTestItem {
  Id id = Isar.autoIncrement;

  /// Заголовок — по нему будет искать глобальный поиск (Этап 5).
  @Index(type: IndexType.value, caseSensitive: false)
  late String title;

  /// Необязательное описание.
  String? description;

  /// Дата создания записи — для сортировки в репозитории.
  DateTime createdAt = DateTime.now();
}
