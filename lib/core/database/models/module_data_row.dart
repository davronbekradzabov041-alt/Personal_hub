import 'package:isar/isar.dart';

part 'module_data_row.g.dart';

/// Одна запись в общем key-value хранилище данных модулей.
///
/// Осознанно НЕ типизированные модели на каждый модуль. По итогам
/// аудита Этапа 6: Isar регистрирует схемы на этапе компиляции, а у
/// внешнего модуля (Этап 11) своего Dart-кода вообще не будет — значит
/// не может быть и своей сгенерированной Isar-схемы. Одна общая
/// generic-коллекция; изоляция данных модулей друг от друга — по
/// полю moduleId на уровне API (ModuleStorageIsar), а не по таблицам.
///
/// Название "Row", а не, например, "Entry" — чтобы не зависеть от
/// того, как именно isar_generator пluralizует имя класса для имени
/// геттера коллекции (`isar.moduleDataRows`); в этой среде нет
/// возможности прогнать build_runner и проверить сгенерированное имя,
/// поэтому выбрано слово с однозначным "+s" множественным числом.
@collection
class ModuleDataRow {
  Id id = Isar.autoIncrement;

  /// Простой (не составной) индекс — см. репозиторий: составной индекс
  /// по (moduleId, key) дал бы более быстрый поиск, но его синтаксис
  /// аннотации не проверен компилятором в этой среде; два простых
  /// индекса и последовательная фильтрация дают корректный результат
  /// ценой чуть меньшей скорости — можно оптимизировать позже.
  @Index()
  late String moduleId;

  @Index()
  late String key;

  late String jsonValue;
}
