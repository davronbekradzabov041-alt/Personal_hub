/// Безопасная замена файла целиком.
library atomic_file_writer;

import 'dart:io';
import 'dart:math';

/// Счётчик для уникальных имён временных файлов.
///
/// Имена временных файлов обязаны быть уникальными на каждый вызов:
/// при фиксированном имени `<target>.tmp` две одновременные записи в
/// одну цель пересекались — второй вызов удалял временный файл первого
/// и подменял цель содержимым, которое первый ещё дописывал. Проверено
/// на этой платформе: в 3 запусках из 12 под конечным именем оказывался
/// файл, собранный из байтов обоих архивов, причём оба вызова
/// сообщали об успехе.
final Random _random = Random();

/// Пишет [bytes] в [target] так, чтобы под конечным именем НИКОГДА не
/// оказался частично записанный файл, а прежний архив переживал любой
/// сбой записи.
///
/// Стратегия: **запись в уникальный временный файл → rename поверх
/// цели**.
///
/// * Данные пишутся только во временный файл в том же каталоге, что и
///   цель (тот же каталог — значит и тот же том, иначе rename вышел бы
///   за пределы файловой системы и не был бы атомарным). Конечный файл
///   при этом не открывается вообще: он либо отсутствует, либо
///   содержит целые прежние данные.
/// * Временное имя уникально на каждый вызов
///   (`<target>.<случайное>.tmp`), поэтому две одновременные записи в
///   одну цель не могут пересечься: каждая пишет в свой файл и
///   подменяет цель только своим, целым содержимым.
/// * Данные сбрасываются на диск (`flush`) ДО подмены, чтобы под
///   конечным именем не оказался файл, чьё содержимое ещё не дошло до
///   носителя.
/// * Подмена выполняется одним системным вызовом [File.rename] поверх
///   существующего файла. Прежний архив заранее НЕ удаляется: на
///   этой платформе (проверено запуском, а не взято из документации)
///   rename заменяет существующий файл целиком, то есть либо подменяет,
///   либо не делает ничего.
/// * Если rename не удалась, прежний архив по определению цел: сбой
///   приходит извне (файл занят посторонним процессом, каталог с
///   таким именем уже существует), а не из-за того, что цель была
///   удалена заранее. Ошибка пробрасывается вызывающему, временный
///   мусор убирается.
///
/// Точные границы гарантии:
///
/// * Гарантируется: под именем [target] никогда не появляется
///   частично записанный архив.
/// * Гарантируется: сбой записи во временный файл не трогает прежний
///   архив — к нему даже не обращаются.
/// * Гарантируется: сбой подмены не уничтожает прежний архив — он
///   либо остаётся на месте целым, либо подмена состоялась целиком и
///   на месте уже новый архив.
/// * НЕ гарантируется: если [target] занят посторонним
///   процессом, подмена не состоится (в Windows — ошибка разделения).
///   Это не потеря данных: вызывающий получает ошибку и сообщает о
///   ней пользователю.
/// * НЕ гарантируется: две одновременные записи в одну цель могут
///   привести к тому, что одна из них завершится ошибкой — в Windows
///   rename поверх цели, которую в этот же момент подменяет другая
///   запись, возвращает «отказано в доступе». Данные при этом не
///   портятся: под конечным именем остаётся целый архив той записи,
///   которая выиграла. Если вызывающему нужно ровно одно содержимое,
///   он обязан сам сериализовать записи в одну цель.
///
/// Формат архива, его манифест и контрольные суммы здесь не
/// участвуют: меняется только порядок операций с файловой системой.
Future<void> writeFileAtomically(File target, List<int> bytes) async {
  final temp = _tempFileFor(target);

  try {
    await temp.writeAsBytes(bytes, flush: true);
  } catch (_) {
    // Конечный файл не был открыт ни разу: прежний архив цел.
    await _deleteQuietly(temp);
    rethrow;
  }

  try {
    // Подмена целиком одним вызовом. Существующий файл НЕ удаляется
    // заранее: в схеме «delete → rename» провал rename стоил бы
    // пользователю единственной копии архива.
    await temp.rename(target.path);
  } catch (_) {
    // Подмена не состоялась, значит цель не изменилась. Убираем мусор
    // и отдаём ошибку вызывающему.
    await _deleteQuietly(temp);
    rethrow;
  }
}

/// Уникальное временное имя рядом с целью.
///
/// Случайная часть нужна именно против гонки двух параллельных записей,
/// а не для красоты: с общим `<target>.tmp` они затирали друг друга.
File _tempFileFor(File target) {
  final unique =
      '${DateTime.now().microsecondsSinceEpoch}-${_random.nextInt(1 << 32)}';
  return File('${target.path}.$unique.tmp');
}

/// Удаляет временный мусор, не давая сбою уборки скрыть результат
/// операции: данные важнее порядка, и вызывающий должен узнать об
/// исходной ошибке, а не о проблеме с уборкой.
Future<void> _deleteQuietly(FileSystemEntity entity) async {
  try {
    if (!await entity.exists()) return;
    // Каталог на месте temp удаляем рекурсивно: прерванный запуск мог
    // оставить после себя одноимённый каталог, и он не должен
    // блокировать следующую запись.
    if (await Directory(entity.path).exists()) {
      await Directory(entity.path).delete(recursive: true);
    } else {
      await File(entity.path).delete();
    }
  } catch (_) {
    // Намеренно игнорируется — см. doc-комментарий.
  }
}