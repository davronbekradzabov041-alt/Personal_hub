/// Состояние модуля в его жизненном цикле.
///
/// installed → enabled → disabled → uninstalled.
///
/// Это состояние отслеживает будущий ModuleManager (Этап 8),
/// а не сам модуль — если бы Module сам хранил своё состояние,
/// было бы два источника правды (объект модуля и менеджер).
/// Здесь — только тип данных.
enum ModuleState {
  /// Модуль скачан/зарегистрирован, но ещё не активен.
  installed,

  /// Модуль активен: показывается в меню, его хуки вызываются,
  /// его SearchProvider (если есть) участвует в глобальном поиске.
  enabled,

  /// Модуль установлен, но временно выключен пользователем —
  /// данные модуля сохраняются, но он не активен.
  disabled,

  /// Модуль полностью удалён. Терминальное состояние.
  uninstalled,
}
