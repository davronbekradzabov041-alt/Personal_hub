import 'module_storage.dart';

/// Маркер версии схемы пользовательских данных модуля (Этап 9.1).
///
/// ## Почему маркер лежит В хранилище модуля
///
/// Только так он едет вместе с данными:
///
/// * в снимок ModuleSnapshotService — значит откатывается вместе с
///   данными, а не остаётся на месте при откате (Этап 9.4);
/// * в .pmb — значит переезжает вместе с архивом и восстанавливается
///   вместе с ним;
/// * стирается при uninstall — значит свежая установка начинается с
///   версии 1, а не наследует маркер удалённого модуля.
///
/// Отдельное поле в ModuleStateRecord или новая Isar-коллекция дали
/// бы три независимых источника правды о версии схемы, которые
/// расходились бы после каждого rollback, restore и удаления.
///
/// ## Отсутствие маркера — это версия 1, а не ошибка
///
/// Модуль, который о версии схемы не говорит, ничего о ней не менял:
/// все данные, записанные до появления миграций, имеют исходную форму.
/// Обратная договорённость («отсутствие значит новую») сделала бы
/// бэкап, снятый до Этапа 9.1, поводом отказать в обновлении.
///
/// ## Почему неверное значение — исключение, а не 1
///
/// Молчаливое превращение мусора в 1 означало бы: миграция не
/// запустится, данные останутся в старой форме, а модуль будет читать
/// их новым кодом. Тихий no-op здесь опаснее явного отказа, поэтому
/// разбор строгий, а ошибка — именованная и ловимая.
class ModuleSchemaMarker {
  ModuleSchemaMarker._();

  /// Ключ маркера в ModuleStorage.
  ///
  /// Префикс `schema:` выбран по той же причине, что и раньше: по
  /// имени ключа видно, что запись служебная и не является частью
  /// пользовательских данных модуля. ModuleStorage.keys() возвращает
  /// общие ключи модуля, и служебная запись не должна выглядеть как
  /// данные.
  static const String key = 'schema:version';

  /// Версия схемы данных, которая подразумевается, пока маркера нет.
  static const int initialVersion = 1;

  /// Читает версию схемы из хранилища модуля.
  ///
  /// Только чтение: отсутствие маркера не пишет его. Иначе обращение
  /// к маркеру (например, чтобы узнать текущую версию, ничего не
  /// меняя) оставляло бы в хранилище запись, а это уже изменение
  /// данных — и no-op перестал бы быть no-op.
  ///
  /// Бросает [ModuleSchemaMarkerException], если маркер есть, но не
  /// является положительным целым числом.
  static Future<int> read(ModuleStorage storage) async {
    final raw = await storage.getString(key);
    if (raw == null) return initialVersion;

    final parsed = int.tryParse(raw.trim());
    if (parsed == null || parsed < initialVersion) {
      throw ModuleSchemaMarkerException(raw);
    }
    return parsed;
  }

  /// Записывает версию схемы в хранилище модуля.
  ///
  /// Пишет строкой — ModuleStorage хранит строки, и разбор не должен
  /// зависеть от того, как именно записано число.
  ///
  /// Вызывающий сам решает, КОГДА писать: маркер, записанный до
  /// переноса данных, превратил бы прерванную на полпути миграцию в
  /// «навсегда завершённую». Об этом — в ModuleDataMigration.
  static Future<void> write(ModuleStorage storage, int version) async {
    if (version < initialVersion) {
      throw ModuleSchemaMarkerException('$version');
    }
    await storage.setString(key, version.toString());
  }
}

/// Маркер версии схемы повреждён или не разбирается.
///
/// Отдельный класс, а не FormatException: вызывающий должен отличать
/// «хранилище модуля содержит непонятный маркер» от «данные вообще не
/// разобрались» — первое требует остановки миграции и разбирательства,
/// второе обычно лечится откатом архива.
class ModuleSchemaMarkerException implements Exception {
  ModuleSchemaMarkerException(this.rawValue);

  /// Значение, которое лежало в маркере (или переданное в write).
  final String rawValue;

  @override
  String toString() =>
      'маркер версии схемы данных (${ModuleSchemaMarker.key}) не разбирается: '
      '"$rawValue" (ожидается положительное целое число)';
}