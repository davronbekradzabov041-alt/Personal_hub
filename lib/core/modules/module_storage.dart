/// Изолированное хранилище одного модуля.
///
/// Только строковый key-value — сознательно не типизированные
/// модели. Согласно аудиту Этапа 6, Isar регистрирует коллекции
/// на этапе компиляции (codegen), поэтому внешний модуль без
/// собственного скомпилированного кода не может завести свою
/// строгую Isar-модель. Generic key-value поверх той же Isar —
/// единственный вариант, одинаково подходящий и встроенным, и
/// внешним модулям, без второй базы данных.
///
/// Реализация поверх Isar (одна общая коллекция с полем moduleId)
/// появится на Этапе 9. Здесь — только контракт.
abstract class ModuleStorage {
  Future<String?> getString(String key);
  Future<void> setString(String key, String value);
  Future<void> remove(String key);

  /// Все ключи модуля — нужно, например, чтобы полностью стереть
  /// данные при удалении модуля (Этап 8/9).
  Future<List<String>> keys();
}
