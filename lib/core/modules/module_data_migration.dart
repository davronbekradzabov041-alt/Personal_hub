import 'module_storage.dart';

/// Один шаг переноса данных модуля к новой версии схемы (Этап 9.1).
///
/// ## Что это и что это не
///
/// Это КОНТРАКТ одного преобразования, а не механизм. Здесь нет и не
/// предполагается: планировщика цепочки шагов, исполнителя, отката,
/// lifecycle-хуков, доступа к Isar. Всё это — работа последующих
/// подэтапов (9.2–9.4), и появление любого из этого здесь означало бы,
/// что шаг начал решать за вызывающего, когда и в каком порядке его
/// запускать.
///
/// ## Смысл fromVersion / toVersion
///
/// Пара — это ОДИН переход между двумя соседними состояниями формы
/// данных, а не «версии, которые эта миграция обслуживает»:
///
/// * `fromVersion` — форма данных ДО шага;
/// * `toVersion`   — форма данных ПОСЛЕ шага.
///
/// Отсюда два правила, которые проверяет вызывающий (ModuleMigrationRunner,
/// Этап 9.2), а не сам шаг:
///
/// * шаг всегда повышает версию: `toVersion > fromVersion`. Шаг,
///   возвращающий данные назад, — это откат, а не миграция, и
///   отдельный механизм отката живёт в другом месте;
/// * шаги выстраиваются в цепочку без разрывов: `toVersion` одного
///   равен `fromVersion` следующего. Поэтому шаг 1→3 законен (он
///   переносит через две версии сразу), а пара 1→2 и 3→4 — нет.
///
/// ## Что шаг обязан гарантировать
///
/// [run] должен быть ИДЕМПОТЕНТНЫМ: повторный вызов на уже перенесённых
/// данных не меняет ничего и не создаёт дублей. Причина не в
/// аккуратности автора, а в том, что вызывающий не может отличить
/// «шаг не выполнялся» от «шаг выполнялся и упал на середине» — оба
/// состояния выглядят одинаково, пока маркер не обновлён. Идемпотентный
/// шаг делает любой из этих двух вариантов безопасным для повтора.
///
/// ## Маркер версии пишет НЕ шаг
///
/// Шаг преобразует данные. Версию схемы записывает вызывающий —
/// [ModuleSchemaMarker] — после того, как [run] успешно вернулся.
/// Если бы шаг писал маркер сам, то место, где решается «перенос
/// завершён», зависело бы от непредсказуемого кода модуля, а
/// прерванный на середине шаг, успевший записать маркер, выглядел бы
/// как навсегда завершённый.
abstract class ModuleDataMigration {
  const ModuleDataMigration();

  /// Версия схемы данных ДО этого шага.
  int get fromVersion;

  /// Версия схемы данных ПОСЛЕ этого шага. Всегда больше [fromVersion].
  int get toVersion;

  /// Переносит данные модуля из [fromVersion] в [toVersion].
  ///
  /// Работает только через [ModuleStorage]: прямой доступ к Isar
  /// сделал бы данные модуля невидимыми для backup, restore и очистки
  /// при uninstall — все они проходят по ключам хранилища.
  ///
  /// Исключения НЕ глотаются. Решение о том, что делать со сбоем
  /// (остановиться, откатиться, повторить при следующем запуске),
  /// принимает вызывающий, и оно не должно молча прятаться внутри
  /// шага.
  ///
  /// Маркер версии ([ModuleSchemaMarker]) в этом методе не пишется.
  Future<void> run(ModuleStorage storage);
}