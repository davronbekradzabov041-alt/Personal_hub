import 'package:flutter/widgets.dart';

/// Вклад модуля в главный экран приложения.
///
/// Граница между ядром и модулями проходит здесь: ядро знает, что
/// модуль МОЖЕТ дать секцию, и умеет её отрисовать — но не знает,
/// что внутри секции, откуда она берёт данные и какие модели
/// использует. Всё это остаётся внутри модуля.
///
/// Секция — это ровно `Widget`. Ни данных, ни моделей, ни колбэков
/// с типом модуля через этот контракт не проходит: иначе ядро снова
/// начало бы узнавать содержимое конкретных модулей, и граница,
/// ради которой контракт существует, разрушилась бы снова.
///
/// Создаётся самим модулем (см. `Module.homeSections`) и отрисовывается
/// ядром только пока модуль активен (`ModuleManager.isEnabled`).
class HomeSection {
  const HomeSection({
    required this.moduleId,
    required this.order,
    required this.builder,
    this.onRefresh,
  });

  /// id модуля-владельца. Секция показывается только когда модуль
  /// с этим id находится в состоянии `enabled` — тем же правилом,
  /// что и его SearchProvider в глобальном поиске.
  final String moduleId;

  /// Порядок секции на главном экране: меньше — выше. В том же
  /// смысле, что и `Module.order` (сортировка по возрастанию).
  final int order;

  /// Строит виджет секции. Вызывается при каждой сборке экрана,
  /// поэтому дешёвое создание виджета здесь нормально, а вот
  /// тяжёлую работу (чтение хранилища) выполнять нельзя — секция
  /// сама решает, когда ей грузить данные.
  final WidgetBuilder builder;

  /// Участие в pull-to-refresh главного экрана.
  ///
  /// Необязателен: статической секции обновлять нечего. Вызывается
  /// ядром последовательно для всех видимых секций, поэтому
  /// реализация не должна рассчитывать на параллельный запуск.
  final Future<void> Function()? onRefresh;
}
