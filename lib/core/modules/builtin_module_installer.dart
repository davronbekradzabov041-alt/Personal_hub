/// ## РЎР±РѕР№ РѕРґРЅРѕРіРѕ РјРѕРґСѓР»СЏ РЅРµ РѕСЃС‚Р°РЅР°РІР»РёРІР°РµС‚ РѕСЃС‚Р°Р»СЊРЅС‹Рµ
///
/// enable() Р±СЂРѕСЃР°РµС‚ ModuleLifecycleError, РµСЃР»Рё С…СѓРє onEnable() РјРѕРґСѓР»СЏ
/// СѓРїР°Р» (СЃРј. ModuleManager.enable). Р”Рѕ Stage 11 СЌС‚Рѕ РёСЃРєР»СЋС‡РµРЅРёРµ
/// РїСЂРѕР»РµС‚Р°Р»Рѕ РЅР°РІРµСЂС… Рё СЂРѕРЅСЏР»Рѕ _bootstrap() С†РµР»РёРєРѕРј: РѕРґРёРЅ СЃР»РѕРјР°РЅРЅС‹Р№
/// РјРѕРґСѓР»СЊ РґРµР»Р°Р» РЅРµСЂР°Р±РѕС‚РѕСЃРїРѕСЃРѕР±РЅС‹Рј РІСЃС‘ РїСЂРёР»РѕР¶РµРЅРёРµ, С…РѕС‚СЏ РѕСЃС‚Р°Р»СЊРЅС‹Рј
/// СЃР»РѕРјР°С‚СЊСЃСЏ Р±С‹Р»Рѕ РЅРµС‡РµРјСѓ.
///
/// РџРѕСЌС‚РѕРјСѓ РєР°Р¶РґС‹Р№ РјРѕРґСѓР»СЊ РѕР±СЂР°Р±Р°С‚С‹РІР°РµС‚СЃСЏ РЅРµР·Р°РІРёСЃРёРјРѕ:
/// - install() РёРґС‘С‚ С‡РµСЂРµР· tryInstall() вЂ” С‚РёРїРёР·РёСЂРѕРІР°РЅРЅС‹Р№ СЂРµР·СѓР»СЊС‚Р°С‚
///   Р±РµР· РёСЃРєР»СЋС‡РµРЅРёСЏ, СЃ СЃРѕР±СЃС‚РІРµРЅРЅС‹Рј РѕС‚РєР°С‚РѕРј РІРЅСѓС‚СЂРё;
/// - enable() РѕР±РѕСЂР°С‡РёРІР°РµС‚СЃСЏ РІ try/catch, Рё РµРіРѕ СЃР±РѕР№ Р·Р°РїРёСЃС‹РІР°РµС‚СЃСЏ РІ
///   РѕС‚С‡С‘С‚, Р° С†РёРєР» РїСЂРѕРґРѕР»Р¶Р°РµС‚СЃСЏ СЃРѕ СЃР»РµРґСѓСЋС‰РёРј РјРѕРґСѓР»РµРј;
/// - СЃРѕСЃС‚РѕСЏРЅРёРµ СЃР±РѕР№РЅРѕРіРѕ РјРѕРґСѓР»СЏ РѕСЃС‚Р°С‘С‚СЃСЏ С‚РµРј, С‡С‚Рѕ Р±С‹Р»Рѕ Р”Рћ РїРѕРїС‹С‚РєРё:
///   РѕС‚РєР°С‚ РґРµР»Р°РµС‚ СЃР°Рј ModuleManager (С…СѓРє РІС‹Р·С‹РІР°РµС‚СЃСЏ РґРѕ РјСѓС‚Р°С†РёРё
///   СЃРѕСЃС‚РѕСЏРЅРёСЏ), Р·РґРµСЃСЊ РЅРёС‡РµРіРѕ РЅРµ РїРѕРґРґРµР»С‹РІР°РµС‚СЃСЏ.
Future<BuiltinInstallReport> ensureBuiltinModulesInstalled(
  ModuleManager manager,
  ModuleStateStore store,
) async {
  final installed = <String>[];
  final failed = <String>[];

  for (final module in ModuleRegistry.modules) {
    final existing = await store.load(module.id);
    if (existing != null) {
      // Восстанавливаем включение только для модулей, сохранённых как installed/enabled,
      // но не для явно отключённых пользователем (state == disabled).
      final shouldEnable = existing.state != 'disabled' &&
          manager.isInstalled(module.id) &&
          !manager.isEnabled(module.id);
      if (shouldEnable) {
        try {
          await manager.enable(module.id);
          installed.add(module.id);
        } on Object catch (_) {
          failed.add(module.id);
        }
      }
      continue;
    }

    final install = await manager.tryInstall(module.id);
    if (!install.isSuccess) {
      failed.add(module.id);
      continue;
    }

    try {
      await manager.enable(module.id);
      installed.add(module.id);
    } on Object catch (_) {
      // РњРѕРґСѓР»СЊ СѓСЃС‚Р°РЅРѕРІР»РµРЅ, РЅРѕ РЅРµ РІРєР»СЋС‡С‘РЅ. Р­С‚Рѕ Р·Р°РєРѕРЅРЅРѕРµ СЃРѕСЃС‚РѕСЏРЅРёРµ:
      // ModuleManager СѓР¶Рµ РѕС‚РєР°С‚РёР» СЃРѕСЃС‚РѕСЏРЅРёРµ Рє С‚РѕРјСѓ, С‡С‚Рѕ Р±С‹Р»Рѕ РґРѕ
      // enable(), Р° РїРѕР»СЊР·РѕРІР°С‚РµР»СЊ РјРѕР¶РµС‚ РїРѕРїСЂРѕР±РѕРІР°С‚СЊ РІРєР»СЋС‡РёС‚СЊ РјРѕРґСѓР»СЊ
      // РІСЂСѓС‡РЅСѓСЋ СЃРѕ СЃС‚СЂР°РЅРёС†С‹ В«РњРѕРґСѓР»РёВ» вЂ” С‚Р°Рј РѕС€РёР±РєР° РїРѕРєР°Р·С‹РІР°РµС‚СЃСЏ
      // СЃРЅСЌРєР±Р°СЂРѕРј, Р° РЅРµ СЌРєСЂР°РЅРѕРј РѕС€РёР±РєРё Р·Р°РїСѓСЃРєР°.
      failed.add(module.id);
    }
  }

  return BuiltinInstallReport(installed: installed, failed: failed);
}
