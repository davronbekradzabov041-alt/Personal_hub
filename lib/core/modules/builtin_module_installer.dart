/// РєР°РєРѕРјСѓ-С‚Рѕ РѕС‚РґРµР»СЊРЅРѕРјСѓ РїСЂРёР·РЅР°РєСѓ РїРѕРЅР°РґРѕР±РёС‚СЃСЏ С‚РѕР»СЊРєРѕ РЅР° Р­С‚Р°РїРµ 11,
/// РєРѕРіРґР° РїРѕСЏРІРёС‚СЃСЏ РІС‚РѕСЂРѕР№ РёСЃС‚РѕС‡РЅРёРє СЂРµРіРёСЃС‚СЂР°С†РёРё; СЃРµР№С‡Р°СЃ РІ СЌС‚РѕРј РЅРµС‚
/// СЃРјС‹СЃР»Р° вЂ” Р»СЋР±РѕР№ Р·Р°СЂРµРіРёСЃС‚СЂРёСЂРѕРІР°РЅРЅС‹Р№ РјРѕРґСѓР»СЊ РѕР±СЂР°Р±Р°С‚С‹РІР°РµС‚СЃСЏ РѕРґРёРЅР°РєРѕРІРѕ.
///
/// Р’С‹Р·С‹РІР°РµС‚СЃСЏ РѕРґРёРЅ СЂР°Р· РїСЂРё СЃС‚Р°СЂС‚Рµ, РџРћРЎР›Р• ModuleStateRestorer.restore():
/// РµСЃР»Рё Сѓ РјРѕРґСѓР»СЏ СѓР¶Рµ РµСЃС‚СЊ СЃРѕС…СЂР°РЅС‘РЅРЅР°СЏ Р·Р°РїРёСЃСЊ СЃРѕСЃС‚РѕСЏРЅРёСЏ вЂ” Р·РЅР°С‡РёС‚, РѕРЅ
/// РєРѕРіРґР°-С‚Рѕ СѓР¶Рµ РїСЂРѕС…РѕРґРёР» С‡РµСЂРµР· install(), Рё РїРѕРІС‚РѕСЂРЅРѕ СѓСЃС‚Р°РЅР°РІР»РёРІР°С‚СЊ
/// РµРіРѕ РЅРµ РЅСѓР¶РЅРѕ (СЌС‚Рѕ Рё РµСЃС‚СЊ В«install СЂР°Р±РѕС‚Р°РµС‚ РѕРґРёРЅ СЂР°Р·В» РёР· Р·Р°РґР°С‡Рё
/// Р­С‚Р°РїР° 10). Р•СЃР»Рё Р·Р°РїРёСЃРё РЅРµС‚ вЂ” СЌС‚Рѕ РїРµСЂРІС‹Р№ Р·Р°РїСѓСЃРє РґР»СЏ СЌС‚РѕРіРѕ РјРѕРґСѓР»СЏ,
/// Рё РѕРЅ СѓСЃС‚Р°РЅР°РІР»РёРІР°РµС‚СЃСЏ Рё СЃСЂР°Р·Сѓ РІРєР»СЋС‡Р°РµС‚СЃСЏ.
