/// РјРѕРґСѓР»СЏ вЂ” СЌС‚Рѕ РѕС‚СЃСѓС‚СЃС‚РІСѓСЋС‰РёР№ РјРѕРґСѓР»СЊ, Р° РЅРµ РЅРµСЂР°Р±РѕС‚Р°СЋС‰РµРµ РїСЂРёР»РѕР¶РµРЅРёРµ.
class BuiltinInstallReport {
  const BuiltinInstallReport({
    required this.installed,
    required this.failed,
  });

  const BuiltinInstallReport.empty()
      : installed = const <String>[],
        failed = const <String>[];

  /// РњРѕРґСѓР»Рё, РґРѕРµС…Р°РІС€РёРµ РґРѕ enabled.
  final List<String> installed;

  /// РњРѕРґСѓР»Рё, РєРѕС‚РѕСЂС‹Рµ РЅРµ СѓРґР°Р»РѕСЃСЊ СѓСЃС‚Р°РЅРѕРІРёС‚СЊ РёР»Рё РІРєР»СЋС‡РёС‚СЊ.
  final List<String> failed;

  bool get hasFailures => failed.isNotEmpty;
  bool get isEmpty => installed.isEmpty && failed.isEmpty;
}

